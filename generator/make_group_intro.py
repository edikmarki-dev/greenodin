def icon(t):
    for k, v in ICON:
        if re.search(k, t.lower()): return v
    return 'star'
def cards(raw_body, titles, h):
    parts = carve(raw_body, titles); lead = parts[0][1].strip(' :'); items = []
    for t, b in parts[1:]:
        b = b.strip(' :').strip(); b = re.sub(r'^[:\s]+', '', b); b = b[:1].upper() + b[1:]
        ss = re.split(r'(?<=[.!?])\s+', b); b = ' '.join(ss[:2]) if len(b) > 230 else b
        items.append({'t': t.strip(' :'), 'x': b, 'i': icon(t)})
    return lead, {'t': 'cards', 'title': h, 'items': items}
def sections(raw, head_cfg, lead_strip=''):
    """head_cfg: [(рівень, текст заголовка, [назви карток] | None)]"""
    raw = cut_tail(raw)
    if lead_strip and raw.startswith(lead_strip): raw = raw[len(lead_strip):].strip()
    parts = carve(raw, [h[1] for h in head_cfg]); blocks = []
    for p in paras(parts[0][1]): blocks.append({'t': 'p', 'x': p})
    for (lvl, h, tit), (_, body) in zip(head_cfg, parts[1:]):
        if tit:
            lead, cd = cards(body, tit, h)
            for p in paras(lead): blocks.append({'t': 'p', 'x': p})
            blocks.append(cd)
            # хвіст після останньої картки, що виглядає як новий абзац, лишається в тексті картки (див. перевірку)
            continue
        blocks.append({'t': lvl, 'x': h.strip(' :')})
        for p in paras(body): blocks.append({'t': 'p', 'x': p})
    return blocks
