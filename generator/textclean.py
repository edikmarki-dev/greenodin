def clean(t):
    if not isinstance(t, str): return t
    t = re.sub(r"Для цього потрібно:\s*[Кк]упити ґрунтовий субстрат.*?GARDEN ?SOIL\.(?: Для посадки[^.¶]*\.)?\s*[Кк]упити (органічне добриво[^.¶]*?GREENODIN BROWN \(рН 5,0\)) (?:та|і) додати",
               r"Для цього підготуйте квітковий субстрат і додайте до нього \1", t, flags=re.S)
    for a, b in GLUE: t = t.replace(a, b)
    buy = bool(BUY.search(t))
    t = BUY.sub('¶', t)
    t = re.sub(r"Унікальні властивості органічного добрива.*$", '', t, flags=re.S).rstrip()
    if buy: t += '¶Як придбати¶' + CONTACT
    for a, b in JUNKS: t = re.sub(a, b, t)
    t = re.sub(r'забезпечує \S*?спрощення', 'забезпечує спрощення', t)
    t = re.sub(r"оформ\w+ замовлення через кошик[^.;]*", "зв'яжіться з нами", t)
    t = re.sub(r"А головне - Гострота перцю.*?в обоих аспектах!", "", t, flags=re.S)
    for a, b in GLUE: t = t.replace(a, b)
    return t
def walk(o, keys=('description', 'subcategory_article')):
    if isinstance(o, dict):
        for k, v in list(o.items()):
            if k in keys and isinstance(v, dict) and 'uk' in v: v['uk'] = clean(v['uk'])
            else: walk(v, keys)
    elif isinstance(o, list):
        for v in o: walk(v, keys)
